#!/usr/bin/env python3
"""Build docs/SOUND_REFS.md: which game data field references which sound event.

Reads the text .blk/.das output of wt_ext_cli (aces / char / game vromfs) and
the event catalog (docs/EVENTS.md or docs/events/*.md). A reference is a
`key:t = "value"` pair whose value equals an event path or an unambiguous event
leaf name. Events that nothing in the data names (crew dialogs, chat) are
started from native code.

    python scripts/sound_refs.py GAMEDATA_ROOT [GAMEDATA_ROOT ...] -o docs/SOUND_REFS.md
"""
import argparse
import glob
import os
import re
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
EVENTS_MD = os.path.join(HERE, '..', 'docs', 'EVENTS.md')

NOISE_KEYS = {
    'name', 'type', 'damageType', 'conditionDamageType', 'trigger', 'group',
    'from', 'to', 'parent', 'material', 'spawnType', 'unitType', 'unitMoveType',
    'hangar_place', 'camoType', 'decorCutProps', 'wep', 'event', 'fxEventName',
    'gun', 'gunnerDm', 'aamGuidanceType', 'engineDmPart', 'engineRoomDmPart', 'trackMesh', 'trackPhysMat',
    '_tracked', 'rotatedTurret', 'turret', 'launchAnimVar', 'guidanceType',
    'SoundMove', 'textToShowInCockpit', 'explosion_dmBlk',
}
NOISE_PREFIXES = ('cls_turret',)

# keys that are sound/fx fields even when their value looks like an event leaf
SOUND_HINT = re.compile(
    r'sfx|sound|siren|voice|TrackSound|EngineName|^Engine$|turret_turn|turretTurn|'
    r'ricochet(?:Fx|Preset|Effect)|ricochetedFx|explosion(?:Event|Fx|Effect)|smokeExplosionFx|'
    r'destructionExplosionFx|alarm|launchSfx|guidanceSfx|hanga?r|event_cockpit|event_start|'
    r'eventStop|eventStart|eventBack|eventLod|eventAOA|next_target|^(?:cockpit|outside|ai|charge)$|'
    r'reload_sound|rainSound|stateAdvanceEventStart',
    re.I,
)


def is_noise_key(key):
    return key in NOISE_KEYS or key.startswith(NOISE_PREFIXES)


def _iter_catalog_files(path):
    events_dir = os.path.join(os.path.dirname(os.path.abspath(path)), 'events')
    if os.path.isdir(events_dir):
        files = sorted(glob.glob(os.path.join(events_dir, '*.md')))
        if files:
            return files
    return [path]


def load_catalog(path):
    events, bank_of = [], {}
    for file_path in _iter_catalog_files(path):
        cur = None
        with open(file_path, encoding='utf-8') as f:
            for line in f:
                if line.startswith('## '):
                    cur = line[3:].strip().split(' ')[0]
                m = re.match(r'\| `event:/([^`]+)`', line)
                if m:
                    bank_of[m.group(1)] = cur
                    events.append(m.group(1))
    return events, bank_of


def build_markdown(events, bank_of, refs, field_values):
    nav = '[← Docs](README.md) · [Events](EVENTS.md) · [Weapons](WEAPONS.md) · [Tanks](TANKS.md) · [Aircraft](AIRCRAFT.md)'
    by_bank = defaultdict(list)
    for e in events:
        by_bank[bank_of[e]].append(e)
    n_ref = sum(1 for e in events if e in refs)
    lines = [
        nav, '',
        '# Sound event references in game data', '',
        'Generated by `scripts/sound_refs.py` from the unpacked `aces`, `char` and `game` vromfs '
        'and [EVENTS.md](EVENTS.md). Each row shows an event, the data fields that name it, and '
        'file counts per field. Events with no row are started from native code by path or GUID '
        '(crew dialogs, chat, music cues).', '',
        '**%d / %d catalog events referenced from data** across **%d banks**.' % (n_ref, len(events), sum(1 for b in by_bank if any(e in refs for e in by_bank[b]))),
        '',
    ]
    for bank in sorted(by_bank):
        evs = by_bank[bank]
        refd = [e for e in evs if e in refs]
        if not refd:
            continue
        lines += ['## %s' % bank, '', '%d events, %d referenced from data files.' % (len(evs), len(refd)), '',
                  '| Event | Referenced by (field: files) |', '| --- | --- |']
        for e in sorted(refd):
            parts = []
            for k, cnt in sorted(refs[e].items(), key=lambda kv_: -sum(kv_[1].values())):
                n_files = len(cnt)
                sample = sorted(cnt)[0]
                parts.append('`%s` ×%d (%s)' % (k, n_files, sample))
            lines.append('| `event:/%s` | %s |' % (e, '; '.join(parts)))
        lines.append('')
    lines += ['## Sound fields whose value is not an event name', '',
              'These fields name presets, banks or composite sets resolved by native code.', '',
              '| Field | Distinct values | Examples |', '| --- | ---: | --- |']
    for k, vals in sorted(field_values.items(), key=lambda kv_: -sum(kv_[1].values()))[:60]:
        lines.append('| `%s` | %d | %s |' % (k, len(vals), ', '.join('`%s`' % v for v, _ in vals.most_common(4))))
    return '\n'.join(lines).rstrip('\n') + '\n', n_ref


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('roots', nargs='+', help='unpacked vromfs roots (aces.vromfs.bin_u, char..., game...)')
    ap.add_argument('-o', '--out', default=os.path.join(HERE, '..', 'docs', 'SOUND_REFS.md'))
    a = ap.parse_args()
    events, bank_of = load_catalog(EVENTS_MD)
    full = {e: e for e in events}
    leaf = defaultdict(list)
    for e in events:
        leaf[e.split('/')[-1].split('.')[0]].append(e)
    amb = {name for name, es in leaf.items() if len(es) > 1}
    kv = re.compile(r'(\w+)\s*:\s*[a-z0-9]+\s*=\s*"([^"]+)"')
    refs = defaultdict(lambda: defaultdict(Counter))   # event -> key -> Counter("root/kind:relpath")
    field_values = defaultdict(Counter)                  # key -> Counter(value) for sound-ish keys
    for root in a.roots:
        root_name = os.path.basename(os.path.normpath(root)).replace('.vromfs.bin_u', '')
        for p in glob.glob(os.path.join(root, '**', '*'), recursive=True):
            kind = p.rsplit('.', 1)[-1]
            if kind not in ('blk', 'das', 'json') or not os.path.isfile(p):
                continue
            try:
                with open(p, encoding='utf-8', errors='replace') as fh:
                    t = fh.read()
            except OSError:
                continue
            rel = os.path.relpath(p, root).replace('\\', '/')
            for k, v in kv.findall(t):
                if is_noise_key(k) and v not in full:
                    continue
                targets = [full[v]] if v in full else (leaf[v] if v in leaf and v not in amb else [])
                if targets and (SOUND_HINT.search(k) or k in ('signalSfxName', 'Engine', 'cockpit', 'outside', 'ai')):
                    for e in targets:
                        refs[e][k]['%s:%s' % (root_name, rel)] += 1
                if not is_noise_key(k) and SOUND_HINT.search(k) and not targets:
                    field_values[k][v] += 1
    text, n_ref = build_markdown(events, bank_of, refs, field_values)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w', encoding='utf-8', newline='\n') as out_f:
        out_f.write(text)
    print('sound refs: %s (%d/%d events referenced from data, %d keys unresolved)'
          % (a.out, n_ref, len(events), len(field_values)))


if __name__ == '__main__':
    main()
